package com.swiftapp_backend.paymentservice.payment.infrastructure.persistence.entity;
import jakarta.persistence.*;
import lombok.*;
import java.time.Instant;
@Entity @Table(name = "payment_event_outbox", indexes = @Index(name = "idx_payment_outbox_pending", columnList = "publishedAt,createdAt"))
@Getter @Setter @NoArgsConstructor
public class PaymentOutboxEntity {
    @Id private String eventId;
    // Database-generated insertion order; UUIDs and event timestamps do not order transitions.
    @org.hibernate.annotations.Generated(event = org.hibernate.generator.EventType.INSERT)
    @Column(name = "delivery_sequence", nullable = false, insertable = false, updatable = false,
            columnDefinition = "bigint generated by default as identity")
    private Long deliverySequence;
    @Column(nullable = false) private Long rideId;
    @Column(nullable = false) private String topic;
    @Column(nullable = false, columnDefinition = "TEXT") private String payload;
    @Column(nullable = false) private Instant createdAt;
    private Instant publishedAt;

    // Delivery metadata is durable; an application restart does not reset retry budgets.
    @Column(name = "delivery_attempts", nullable = false, columnDefinition = "integer default 0")
    private int deliveryAttempts;
    private Instant nextAttemptAt;
    private Instant leaseUntil;
    @Column(length = 36) private String deliveryToken;
    private Instant quarantinedAt;
    @Column(length = 160) private String lastFailureType;
}
