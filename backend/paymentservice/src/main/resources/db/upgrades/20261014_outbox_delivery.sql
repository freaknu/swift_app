-- Additive/idempotent upgrade for existing PostgreSQL development databases.
-- Apply before boot when using production ddl-auto=validate.
-- An identity column gives existing rows distinct durable sequence values and
-- gives future inserts monotonic ordering even when timestamps/UUIDs collide.
ALTER TABLE payment_event_outbox ADD COLUMN IF NOT EXISTS delivery_sequence bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE payment_event_outbox ADD COLUMN IF NOT EXISTS delivery_attempts integer DEFAULT 0;
UPDATE payment_event_outbox SET delivery_attempts = 0 WHERE delivery_attempts IS NULL;
ALTER TABLE payment_event_outbox ALTER COLUMN delivery_attempts SET DEFAULT 0;
ALTER TABLE payment_event_outbox ALTER COLUMN delivery_attempts SET NOT NULL;
ALTER TABLE payment_event_outbox ADD COLUMN IF NOT EXISTS next_attempt_at timestamp with time zone;
ALTER TABLE payment_event_outbox ADD COLUMN IF NOT EXISTS lease_until timestamp with time zone;
ALTER TABLE payment_event_outbox ADD COLUMN IF NOT EXISTS delivery_token varchar(36);
ALTER TABLE payment_event_outbox ADD COLUMN IF NOT EXISTS quarantined_at timestamp with time zone;
ALTER TABLE payment_event_outbox ADD COLUMN IF NOT EXISTS last_failure_type varchar(160);
CREATE INDEX IF NOT EXISTS idx_payment_event_outbox_due
    ON payment_event_outbox (quarantined_at, next_attempt_at, lease_until);
CREATE INDEX IF NOT EXISTS idx_payment_outbox_ride_order ON payment_event_outbox (ride_id, published_at, delivery_sequence);
